"""Build docs/MODEL-BENCH.md from the JSON results. usage: report.py [results_dir] [verdicts.json]"""
import json, sys
from pathlib import Path
from common import MODELS, OUT, REPO

res = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
verd = json.loads(Path(sys.argv[2]).read_text()) if len(sys.argv) > 2 else {}
D = {}
for m in MODELS:
    d = res / m
    D[m] = {n: json.loads((d / f"{n}.json").read_text()) for n in ("engine_status", "lines", "conv", "structured", "tools", "speed", "voice") if (d / f"{n}.json").exists()}
    if (d / "struct.json").exists():
        D[m]["struct"] = json.loads((d / "struct.json").read_text())


def pct(x):
    return "n/a" if x is None else f"{100 * x:.0f}%"


def f(x, n=2):
    return "n/a" if x is None else f"{x:.{n}f}"


def g(m, *path, default=None):
    cur = D[m]
    for p in path:
        if cur is None or p not in cur:
            return default
        cur = cur[p]
    return cur


def row(label, fn):
    return "| " + label + " | " + " | ".join(fn(m) for m in MODELS) + " |"


L = []
L.append("# Model bench: the four HermesVoice models through the engine\n")
L.append("Generated by `bench/models/report.py` from `bench/models/` results. Every call goes through the engine's proxy "
         "(`127.0.0.1:47480`, llama-server b12680, `--jinja`, `--reasoning off`, 3 slots, `--no-kv-unified`) on an RTX 5080 16 GB, one model at a time. "
         "Lines, conversation, intent and reflection use the agent's own code (`hermesvoice_agent`: `build_prefix`, `line_pass`, `speak`, `sanitize_line`, `intent_messages`, `REFLECT_SCHEMA`, `HttpLLM`), imported, not re-implemented.\n")
L.append("Method notes: grammar and spelling are checked offline with `pyspellchecker` plus a rule set (no Java in this environment, so `language_tool_python` could not run); both under-report subtle grammar faults and over-report slang, so read them as a floor on trouble. "
         "The invented-entity check flags capitalised words that are not in the prompt. Prompts are built from the M0 fixtures (6 pawns, 30 scenes, 20 grim); the fixed bio, voice card and memories come from the fixtures, the block layout from `core/prompt.py`.\n")

L.append("## Comparison\n")
L.append("| | " + " | ".join(MODELS) + " |")
L.append("|---|" + "---|" * len(MODELS))
L.append(row("**Lines** (n=100 raw all-checks pass)", lambda m: pct(g(m, "lines", "summary", "raw_all_pass"))))
L.append(row("sanitizer drop rate (grim only)", lambda m: f"{pct(g(m, 'lines', 'summary', 'sanitizer_drop_rate'))} ({pct(g(m, 'lines', 'summary', 'grim_drop_rate'))})"))
L.append(row("refusal or moralising on grim lines", lambda m: pct(g(m, "lines", "summary", "grim_raw_refusal_rate"))))
L.append(row("spelling ok / grammar ok (raw)", lambda m: f"{pct(g(m, 'lines', 'summary', 'raw_pass', 'spelling'))} / {pct(g(m, 'lines', 'summary', 'raw_pass', 'grammar'))}"))
L.append(row("no invented names / ends in terminal punctuation", lambda m: f"{pct(g(m, 'lines', 'summary', 'raw_pass', 'no_invented'))} / {pct(g(m, 'lines', 'summary', 'raw_pass', 'terminal'))}"))
L.append(row("median line length (tokens)", lambda m: f(g(m, "lines", "summary", "tokens_median"), 0)))
L.append(row("duplicate lines of 100", lambda m: str(g(m, "lines", "summary", "duplicate_lines"))))
L.append(row("**Conversation** turn drop rate", lambda m: pct(g(m, "conv", "summary", "turn_drop_rate"))))
L.append(row("exchanges with a loop (of 10)", lambda m: str(g(m, "conv", "summary", "repetition_loop_exchanges"))))
L.append(row("turns that answer the previous (heuristic)", lambda m: pct(g(m, "conv", "summary", "answers_previous_rate"))))
L.append(row("writes the other speaker's line", lambda m: pct(g(m, "conv", "summary", "writes_other_line_rate"))))
L.append(row("**Intent** accuracy: grammar (agent) / free", lambda m: f"{pct(g(m, 'struct', 'intent', 'summary', 'grammar', 'accuracy'))} / {pct(g(m, 'struct', 'intent', 'summary', 'free', 'accuracy'))}"))
L.append(row("intent latency median (grammar)", lambda m: f"{f(g(m, 'struct', 'intent', 'summary', 'grammar', 'latency_median_s'), 3)} s"))
L.append(row("intent json_schema mode: json-valid / schema-valid", lambda m: f"{pct(g(m, 'struct', 'intent', 'summary', 'schema', 'valid_json_rate'))} / {pct(g(m, 'struct', 'intent', 'summary', 'schema', 'schema_valid_rate'))}"))
L.append(row("**Reflection JSON** parse / schema-valid / accepted (20)", lambda m: f"{pct(g(m, 'struct', 'reflection', 'summary', 'json_parse_rate'))} / {pct(g(m, 'struct', 'reflection', 'summary', 'schema_valid_rate'))} / {pct(g(m, 'struct', 'reflection', 'summary', 'accepted_by_agent_rate'))}"))
L.append(row("reflection latency median", lambda m: f"{f(g(m, 'struct', 'reflection', 'summary', 'latency_median_s'), 1)} s"))
for ch in ("auto", "required"):
    L.append(row(f"**Tools** ({ch}) parse / right tool (single) / args valid", lambda m, ch=ch: f"{pct(g(m, 'tools', ch, 'summary', 'tool_calls_parse_rate'))} / {pct(g(m, 'tools', ch, 'summary', 'right_tool_rate_single'))} / {pct(g(m, 'tools', ch, 'summary', 'args_valid_rate'))}"))
    L.append(row(f"tools ({ch}) two-call right / no-tool right", lambda m, ch=ch: f"{pct(g(m, 'tools', ch, 'summary', 'right_tools_rate_double'))} / {pct(g(m, 'tools', ch, 'summary', 'no_tool_correct_rate'))}"))
    L.append(row(f"tools ({ch}) hallucinated names / tool text left in content", lambda m, ch=ch: f"{g(m, 'tools', ch, 'summary', 'hallucinated_tool_calls')} / {g(m, 'tools', ch, 'summary', 'tool_call_text_in_content')}"))
    L.append(row(f"tools ({ch}) round 2 non-empty / http ok", lambda m, ch=ch: f"{pct(g(m, 'tools', ch, 'summary', 'round2_ok_rate'))} / {pct(g(m, 'tools', ch, 'summary', 'round2_http_ok_rate'))}"))


def sp(m, case, key, sub="median", nd=3):
    v = g(m, "speed", case, "summary", key)
    return f"{f(v[sub], nd)}" if v else "n/a"


for case, lab in (("cold_erased", "cold (slot erased)"), ("cold_new_pawn", "cold, new pawn prefix"), ("warm", "warm (cached prefix)"), ("concurrent3_warm", "3 slots at once, warm")):
    L.append(row(f"**Speed** {lab}: TTFT med / p90 (s)", lambda m, c=case: f"{sp(m, c, 'ttft_s')} / {sp(m, c, 'ttft_s', 'p90')}"))
    L.append(row(f"speed {lab}: decode tok/s med / p90", lambda m, c=case: f"{sp(m, c, 'decode_tps', nd=0)} / {sp(m, c, 'decode_tps', 'p90', 0)}"))
L.append(row("speed warm: cached tokens (median) / new prompt tokens", lambda m: f"{sp(m, 'warm', 'cache_n', nd=0)} / {sp(m, 'warm', 'prompt_n', nd=0)}"))
L.append(row("speed cold: prompt tok/s med / p90", lambda m: f"{sp(m, 'cold_erased', 'prompt_tps', nd=0)} / {sp(m, 'cold_erased', 'prompt_tps', 'p90', 0)}"))
L.append(row("speed cold: effective prefill tok/s (median)", lambda m: sp(m, "cold_erased", "effective_prefill_tps", nd=0)))
L.append(row("speed ~30-token line, warm: total s med / p90", lambda m: f"{sp(m, 'long_warm', 'total_s')} / {sp(m, 'long_warm', 'total_s', 'p90')}"))
L.append(row("speed ~30-token line, cold: total s med / p90", lambda m: f"{sp(m, 'long_cold_erased', 'total_s')} / {sp(m, 'long_cold_erased', 'total_s', 'p90')}"))
L.append(row("speed ~30-token line: median tokens made", lambda m: sp(m, "long_warm", "pred_n", nd=0)))
L.append(row("**Voice** pawn-ID accuracy (chance 17%) / slop rate", lambda m: f"{pct(g(m, 'voice', 'summary', 'pawn_id_acc_mean'))} / {pct(g(m, 'voice', 'summary', 'slop_rate'))}"))
L.append(row("engine shape (slots x ctx, KV)", lambda m: (lambda s: f"{s['slots']} x {s['ctx_per_slot']}, {s['kv_type']}" if s else "n/a")(g(m, "engine_status", "shape"))))
L.append(row("VRAM used with model loaded (MiB)", lambda m: str(g(m, "engine_status", "vram_mib"))))
L.append(row("**Verdict**", lambda m: verd.get(m, {}).get("verdict", "pending")))
L.append("")

for m in MODELS:
    L.append(f"## {m}\n")
    v = verd.get(m, {})
    if v:
        L.append(f"**Verdict: {v['verdict']}.** {v.get('why', '')}\n")
        for c in v.get("caveats", []):
            L.append(f"- {c}")
        L.append("")
    s = g(m, "lines", "summary")
    if s:
        L.append("### Lines\n")
        L.append(f"{s['n']} lines ({s['grim_n']} grim). Raw pass rate per check:\n")
        L.append("| check | raw | after sanitizer |\n|---|---|---|")
        for k, val in s["raw_pass"].items():
            L.append(f"| {k} | {pct(val)} | {pct(s.get('sanitized_pass', {}).get(k))} |")
        L.append(f"\nSanitizer drop rate {pct(s['sanitizer_drop_rate'])} (reasons: {s['drop_reasons']}). The model keeps writing past the newline on {pct(s['keeps_writing_after_newline'])} of lines (harmless: the agent stops at `\\n`).\n")
        L.append("12 sample lines (raw -> sanitized):\n")
        for x in s["samples"]:
            L.append(f"- `{x['pawn']}/{x['scene']}`: {x['raw']!r}" + (f" -> dropped ({x['drop']})" if x["drop"] else ""))
        rows = g(m, "lines", "rows")
        bad = [r for r in rows if not all(r["raw_checks"].values()) or not r["kept"]]
        L.append(f"\nFailures, verbatim ({len(bad)} lines with a failed check or a drop; first 10):\n")
        for r in bad[:10]:
            fails = [k for k, ok in r["raw_checks"].items() if not ok]
            L.append(f"- `{r['pawn']}/{r['scene']}` failed {fails or '-'}, sanitizer: {r['drop_reason'] or 'kept'}: {r['raw']!r}")
        L.append("")
        probs = {"spelling": [], "grammar": [], "invented": []}
        for r in rows:
            for k in probs:
                if r["raw_problems"][k]:
                    probs[k].append((r["raw"], r["raw_problems"][k]))
        for k, lst in probs.items():
            if lst:
                L.append(f"{k} flags ({len(lst)}): " + "; ".join(f"{t!r} -> {p}" for t, p in lst[:4]) + "\n")
    c = g(m, "conv", "summary")
    if c:
        L.append("### Conversation\n")
        L.append(f"{c['exchanges']} exchanges, {c['turns']} turns; drop rate {pct(c['turn_drop_rate'])}; complete exchanges {pct(c['complete_exchanges'])}; answers previous {pct(c['answers_previous_rate'])}; "
                 f"writes the other's line {pct(c['writes_other_line_rate'])}; exchanges with a repetition loop {c['repetition_loop_exchanges']}.\n")
        looped = [r for r in g(m, "conv", "rows") if r["rep"]["loop"]][:2]
        for r in looped:
            L.append(f"Loop example `{r['scene']}`:\n")
            for x in r["turns"]:
                L.append(f"> {x['speaker']}: {x.get('text') or 'DROPPED ' + x['dropped']}")
            L.append("")
        for e in c["examples"][:1]:
            L.append(f"Example `{e['scene']}`:\n")
            for sp_, t in e["turns"]:
                L.append(f"> {sp_}: {t}")
            L.append("")
    st = g(m, "struct")
    if st:
        L.append("### Structured output\n")
        for mode, x in st["intent"]["summary"].items():
            L.append(f"- intent `{mode}`: json-valid {pct(x['valid_json_rate'])}, schema/label-valid {pct(x['schema_valid_rate'])}, accuracy {pct(x['accuracy'])}, latency median {f(x['latency_median_s'], 3)} s, p90 {f(x['latency_p90_s'], 3)} s")
        gm = st["intent"]["summary"]["grammar"]["confusions"][:6]
        L.append("\nIntent misses (grammar mode), label -> predicted: " + "; ".join(f"{a} -> {b}: {l!r}" for a, b, l in gm) + "\n")
        r = st["reflection"]["summary"]
        L.append(f"- reflection JSON ({r['runs']} runs): parse {pct(r['json_parse_rate'])}, schema-valid {pct(r['schema_valid_rate'])}, pydantic {pct(r['pydantic_ok_rate'])}, accepted by `run_reflection` {pct(r['accepted_by_agent_rate'])}, truncated at the 500-token cap {r['truncated_at_cap']}, median {f(r['latency_median_s'], 1)} s / {f(r['tokens_median'], 0)} tokens")
        for fl in r["failures"][:3]:
            L.append(f"  - failure ({fl['pawn']}): {fl['err']!r} raw: {fl['raw']!r}")
        L.append("\nThe agent has no separate memory-JSON schema: memories are one-line text (`_ask_line`) and merges ride inside `REFLECT_SCHEMA.merge`, so the reflection runs cover it.\n")
    t = g(m, "tools")
    if t:
        L.append("### Tool calls\n")
        for ch in ("auto", "required"):
            x = t[ch]["summary"]
            L.append(f"- `tool_choice={ch}`: parse {pct(x['tool_calls_parse_rate'])}, calls present on action prompts {pct(x['tool_calls_present_on_action_prompts'])}, right tool (single) {pct(x['right_tool_rate_single'])}, "
                     f"two-call prompts {pct(x['right_tools_rate_double'])}, no-tool prompts right {pct(x['no_tool_correct_rate'])}, args valid {pct(x['args_valid_rate'])}, hallucinated names {x['hallucinated_tool_calls']} {x['hallucinated_names']}, "
                     f"tool syntax left in content {x['tool_call_text_in_content']}, round 2 http ok {pct(x['round2_http_ok_rate'])} / non-empty {pct(x['round2_ok_rate'])}")
        for ch in ("auto", "required"):
            fl = t[ch]["summary"]["failures"][:4]
            if fl:
                L.append(f"\nFailures ({ch}), verbatim:\n")
                for x in fl:
                    L.append(f"- prompt {x['prompt']!r}; expected {x['expected']}, called {x['called']}, content {x['content']!r}, args {x['args']}")
        L.append("")
    s = g(m, "speed")
    if s:
        L.append("### Speed\n")
        L.append("| case | n | TTFT med / p90 s | total med / p90 s | decode tok/s med / p90 | prompt tok/s med / p90 | cached tok med | new prompt tok med | tokens made med |\n|---|---|---|---|---|---|---|---|---|")
        for case in ("cold_erased", "cold_new_pawn", "warm", "concurrent3_cold", "concurrent3_warm", "long_cold_erased", "long_warm", "long_concurrent3_warm"):
            if case in s:
                x = s[case]["summary"]
                S = lambda k, n=3, sub="median": f(x[k][sub], n) if x.get(k) else "n/a"
                L.append(f"| {case} | {x['n']} | {S('ttft_s')} / {S('ttft_s', 3, 'p90')} | {S('total_s')} / {S('total_s', 3, 'p90')} | {S('decode_tps', 0)} / {S('decode_tps', 0, 'p90')} | {S('prompt_tps', 0)} / {S('prompt_tps', 0, 'p90')} | {S('cache_n', 0)} | {S('prompt_n', 0)} | {S('pred_n', 0)} |")
        if "concurrent3_warm" in s:
            L.append(f"\n3 slots at once, warm: aggregate decode {f(s['concurrent3_warm']['aggregate_decode_tps_median'], 0)} tok/s, round wall {f(s['concurrent3_warm']['round_wall_s']['median'])} s median.\n")
    vo = g(m, "voice", "summary")
    if vo:
        L.append("### Voice distinctness\n")
        L.append(f"Pawn-ID accuracy from lines alone {pct(vo['pawn_id_acc_mean'])} (chance {pct(vo['chance'])}), slop-phrase rate {pct(vo['slop_rate'])}, duplicate lines {vo['dup_lines']}. Samples:\n")
        for p, ls in vo["samples"].items():
            L.append(f"- {p}: " + " / ".join(repr(x) for x in ls[:3]))
        L.append("")

extra = Path(sys.argv[3]).read_text() if len(sys.argv) > 3 else ""
L.append(extra)
(REPO / "docs/MODEL-BENCH.md").write_text("\n".join(L))
print("wrote docs/MODEL-BENCH.md")
